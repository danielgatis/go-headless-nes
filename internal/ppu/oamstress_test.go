// sample2004 mirrors what a $2004 read ending on the current dot returns.
func sample2004(p *PPU) byte {
	if p.Scanline <= 239 && p.isRenderingEnabled() {
		if (p.Cycle >= 257 && p.Cycle <= 340) || p.Cycle == 0 {
			return p.SecondarySpriteRAM[p.SecondaryOamAddr&0x1F]
		}
		return p.OamCopybuffer
	}
	return p.SpriteRAM[p.SpriteRAMAddr]
}

// TestOAMStressKey1 replays AccuracyCoin's "$2004 Stress Test" answer key 1
// against the bare PPU: OAM holds $FF..$00 descending and every dot of
// scanline 128 is sampled. Divergences print with their dot number.
func TestOAMStressKey1(t *testing.T) {
	p := New(&stubBoard{})
	for i := range 256 {
		v := byte(0xFF - i)
		if i&3 == 2 {
			// Attribute bytes lose bits 2-4 on write ($2004/DMA both mask).
			v &= 0xE3
		}
		p.SpriteRAM[i] = v
	}
	p.WriteRegister(0x2001, 0x18) // enable background + sprites

	got := make([]byte, 341)
	for range 400_000 {
		p.Tick()
		if p.Scanline == 128 {
			got[p.Cycle] = sample2004(p)
			if p.Cycle == 340 {
				break
			}
		}
	}

	bad := 0
	for dot := range 341 {
		if got[dot] != answerKey1[dot] {
			if bad < 40 {
				t.Errorf("dot %3d: got %02X want %02X", dot, got[dot], answerKey1[dot])
			}
			bad++
		}
	}
	if bad > 0 {
		t.Errorf("%d/341 dots diverge", bad)
	}
}
